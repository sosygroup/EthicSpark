import { Info } from "./Help";
import { fingerprint, reportNotice } from "./notification-store";
import { openNotifications } from "./NotificationCenter";
import { useEffect, useState } from "react";
import VisualImage from "./VisualImage";
import { downloadArtifact, normalizeMermaid } from "./visual-utils";
import {
  checkForAppUpdate,
  getUpdateState,
  isModuleLoadError,
} from "./app-update";
type Failure = "syntax" | "module" | "render";
class DiagramFailure extends Error {
  constructor(
    readonly kind: Failure,
    detail = "",
  ) {
    super(detail || kind);
  }
}

// Mermaid has shared configuration and parser state. Serialize work, including parsing.
let queue: Promise<unknown> = Promise.resolve();
async function renderDiagram(code: string): Promise<string> {
  const task = queue
    .catch(() => {})
    .then(async () => {
      const module = await import("mermaid");
      if (!module?.default) throw new DiagramFailure("module");
      const mermaid = module.default;
      mermaid.initialize({
        startOnLoad: false,
        securityLevel: "strict",
        theme: "neutral",
        flowchart: { htmlLabels: false },
        fontFamily: "Arial, sans-serif",
      });
      try {
        await mermaid.parse(code);
      } catch (error) {
        if (isModuleLoadError(error) || getUpdateState() !== "current")
          throw new DiagramFailure(
            "module",
            error instanceof Error ? error.message : String(error),
          );
        throw new DiagramFailure(
          "syntax",
          error instanceof Error ? error.message : String(error),
        );
      }
      const host = document.createElement("div");
      host.className = "mermaid-render-host";
      host.setAttribute("aria-hidden", "true");
      document.body.appendChild(host);
      try {
        const result = await mermaid.render(
          "diagram-" + crypto.randomUUID(),
          code,
          host,
        );
        return result.svg;
      } finally {
        // Also remove Mermaid's temporary error drawing if layout/render fails.
        host.remove();
      }
    });
  queue = task;
  return task;
}
export default function Diagram({ code }: { code: string }) {
  const [result, setResult] = useState<{
    code: string;
    svg: string;
    error: Failure | null;
  } | null>(null);
  const normalized = normalizeMermaid(code);
  const current = result?.code === code ? result : null;
  useEffect(() => {
    let active = true;
    void renderDiagram(normalized)
      .then((svg) => {
        if (active) setResult({ code, svg, error: null });
      })
      .catch((error: unknown) => {
        const kind: Failure =
          error instanceof DiagramFailure
            ? error.kind
            : isModuleLoadError(error) || getUpdateState() !== "current"
              ? "module"
              : "render";
        if (kind === "module") void checkForAppUpdate(true, error);
        if (active) {
          setResult({ code, svg: "", error: kind });
          if (kind !== "module")
            reportNotice({
              key: "diagram:" + kind + ":" + fingerprint(code),
              source: "Diagram preview",
              severity: "warning",
              title:
                kind === "syntax"
                  ? "Diagram source needs correction"
                  : "A diagram could not be rendered",
              explanation:
                kind === "syntax"
                  ? "Mermaid could not interpret this diagram's text. The source may have been generated by a model or supplied in a document. It needs review; this does not imply a failure of the rest of the application."
                  : "The diagram renderer could not create this preview. The cause may be unsupported content, a rendering limit or an integration problem; it is not yet established.",
              nextStep:
                "Use Diagram source in the conversation to inspect or download the original. Correct the syntax or ask the model to regenerate the diagram.",
              details: error instanceof Error ? error.message : String(error),
            });
        }
      });
    return () => {
      active = false;
    };
  }, [code, normalized]);
  return (
    <figure className="diagram-result">
      {current?.svg ? (
        <>
          <VisualImage
            name="Generated diagram"
            src={
              "data:image/svg+xml;charset=utf-8," +
              encodeURIComponent(current.svg)
            }
          />
          <button
            type="button"
            onClick={() =>
              downloadArtifact({
                name: "diagram.svg",
                mediaType: "image/svg+xml",
                content: current.svg,
              })
            }
          >
            Download SVG
          </button>
        </>
      ) : current?.error ? (
        <button
          type="button"
          className="notification-reference"
          onClick={openNotifications}
        >
          Preview unavailable · view Notifications
        </button>
      ) : (
        <p role="status">Rendering diagram…</p>
      )}
      {/^(graph|flowchart)(TB|TD|BT|RL|LR)\b/.test(code.trim()) && (
        <small>
          Preview corrected a missing space in the diagram header. The original
          source is preserved.
        </small>
      )}
      <details>
        <summary>
          Diagram source <Info topic="diagram" />
        </summary>
        <pre>{code}</pre>
      </details>
      <button
        type="button"
        onClick={() =>
          downloadArtifact({
            name: "diagram.mmd",
            mediaType: "text/vnd.mermaid",
            content: code,
          })
        }
      >
        Download source
      </button>
    </figure>
  );
}
